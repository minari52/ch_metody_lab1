import math

def print_section(title):
    print(f"\n{'='*10} {title} {'='*10}")

# ==========================================
# ЗАДАНИЕ 1) Определить, какое равенство точнее
# ==========================================
print_section("1) Точность равенств")

# Дано: 60/44 ≈ 1.364 и sqrt(152) ≈ 12.33
# Точное значение (эталон):
true_val_1 = 60 / 44
true_val_2 = math.sqrt(152)

# Значения из условия:
approx_val_1 = 1.364
approx_val_2 = 12.33

# Абсолютная погрешность (разница по модулю):
abs_err_1 = abs(true_val_1 - approx_val_1)
abs_err_2 = abs(true_val_2 - approx_val_2)

# Относительная погрешность (в процентах):
# E = (Абс.погр / Точное значение) * 100%
rel_err_1 = (abs_err_1 / true_val_1) * 100
rel_err_2 = (abs_err_2 / true_val_2) * 100

print(f"1. 60/44:")
print(f"   Точное значение: {true_val_1:.6f}")
print(f"   Абс. погрешность: {abs_err_1:.6f}")
print(f"   Отн. погрешность: {rel_err_1:.4f}%")

print(f"\n2. sqrt(152):")
print(f"   Точное значение: {true_val_2:.6f}")
print(f"   Абс. погрешность: {abs_err_2:.6f}")
print(f"   Отн. погрешность: {rel_err_2:.4f}%")

# Вывод:
if rel_err_1 < rel_err_2:
    print("\n-> Первое равенство точнее (относительная погрешность меньше).")
else:
    print("\n-> Второе равенство точнее (относительная погрешность меньше).")


# ==========================================
# ЗАДАНИЕ 2) Округлить сомнительные цифры
# ==========================================
print_section("2) Округление и погрешность")

# Дано: Число 5115, Относительная погрешность (О.п.) = 0.21% (0.0021 в долях)
num_raw = 5115
rel_err_given = 0.21 / 100  # Переводим проценты в доли

# 1. Находим абсолютную погрешность до округления: Delta = X * E
abs_err_given = num_raw * rel_err_given
print(f"Абсолютная погрешность исходного числа: {abs_err_given:.4f}")

# 2. Определяем, сколько цифр оставить.
# Если абс. погрешность меньше 0.5, то верны единицы (округление до целого).
# Если погрешность ~10, то верны десятки.
# Тут погрешность ~10.74. Значит, сомнительна цифра единиц.
# Оставляем верные знаки -> округляем до десятков.
# 5115 -> 5120.

rounded_num = 5120

# 3. Находим новую абсолютную погрешность результата.
# Погрешность округления = |Округленное - Исходное| + Исходная абс. погрешность
# (Иногда считают просто половину цены деления, но здесь через полную формулу надежнее)
# Но по стандартной методике: Абс.погр результата = Абс.погр числа + погрешность округления
rounding_error = abs(rounded_num - num_raw)
total_abs_err_rounded = rounding_error + abs_err_given

print(f"Округленное число (до верных знаков): {rounded_num}")
print(f"Погрешность округления: {rounding_error}")
print(f"Абсолютная погрешность результата: {total_abs_err_rounded}")


# ==========================================
# ЗАДАНИЕ 3) Найти предельные погрешности (48)
# ==========================================
print_section("3) Предельные погрешности числа 48")

# Дано: 48. Все цифры верные.
# Если число задано целым и все цифры верные, то абсолютная погрешность 
# не превышает половины последнего разряда (единицы).
# Delta_a = 0.5

val_3 = 48
limit_abs_err = 0.5  # Предельная абсолютная погрешность

# Предельная относительная погрешность = (Delta_a / X) * 100%
limit_rel_err = (limit_abs_err / val_3) * 100

print(f"Число: {val_3}")
print(f"Предельная абсолютная погрешность: {limit_abs_err}")
print(f"Предельная относительная погрешность: {limit_rel_err:.4f}%")


# ==========================================
# ЗАДАНИЕ 4) Вычислить и определить погрешность
# ==========================================
print_section("4) Вычисление сложной формулы")

# Дано:
# X = (a + b) * c / (d + 0.5 * e)
# a=2.16, b=3.58, c=2.96, d=5.52, e=5.58
# Все числа даны в верных знаках. Значит, у них у всех абс. погрешность = 0.005 (половина последнего знака).
# (Так как у всех два знака после запятой).

a, b, c, d, e = 2.16, 3.58, 2.96, 5.52, 5.58
delta = 0.005 # Погрешность каждого аргумента

# 1. Вычисляем значение X
# Числитель и знаменатель отдельно для удобства
numerator = (a + b) * c
denominator = d + 0.5 * e
X = numerator / denominator

print(f"Значение X = {X:.6f}")

# 2. Вычисляем относительную погрешность по методу границ (или логарифмическому методу)
# Формула: E_X = Сумма (|производная по переменной| * delta / X)
# Но проще через логарифмы:
# ln(X) = ln(a+b) + ln(c) - ln(d+0.5e)
# dX/X = da/(a+b) + db/(a+b) + dc/c - (dd + 0.5*de)/(d+0.5e)

# Считаем предельную относительную погрешность (максимальную):
# E = (delta / (a+b)) + (delta / (a+b)) + (delta / c) + (delta / (d+0.5e)) + (0.5*delta / (d+0.5e))
# Упрощаем: сумма всех модулей вкладов.

# Вклад от (a+b): погрешность суммы = delta + delta = 2*delta.
# Отн. погрешность числителя = (2*delta)/(a+b) + delta/c
rel_err_num = (2 * delta) / (a + b) + delta / c

# Вклад от знаменателя (d + 0.5e): погрешность = delta + 0.5*delta = 1.5*delta
# Отн. погрешность знаменателя = (1.5 * delta) / denominator
rel_err_den = (1.5 * delta) / denominator

# Общая относительная погрешность
total_rel_err = rel_err_num + rel_err_den

# Абсолютная погрешность результата
total_abs_err_X = X * total_rel_err

print(f"Относительная погрешность (в %): {total_rel_err*100:.2f}%")
print(f"Абсолютная погрешность: {total_abs_err_X:.5f}")

# 3. Запись результата в верных знаках
# Смотрим на абсолютную погрешность. Если она ~0.06, то верны десятые (0.1).
# Значит, округляем X до десятых.
print(f"Результат с погрешностью: X = {X:.2f} ± {total_abs_err_X:.2f}")