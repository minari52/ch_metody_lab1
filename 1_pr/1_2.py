def horner_scheme(coeffs, x):
    """Схема Горнера для вычисления значения полинома и его производной"""
    # coeffs передаются от старшей степени к младшей: [1, -2, 10, 8]
    n = len(coeffs)
    b = coeffs[0]
    for i in range(1, n):
        b = b * x + coeffs[i]
    return b

