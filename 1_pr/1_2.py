print("\n--- ЗАДАНИЕ 2. Отделение и уточнение корней (Метод итерации) ---")

# --- Уравнение 1: x^3 - 2x^2 + 10x + 8 = 0 ---
# Отделение корня: P(-1) = -5, P(0) = 8. Значит корень на интервале [-1, 0].
# Метод итерации требует привести уравнение к виду x = f(x).
# f(x) = -(x^3 - 2x^2 + 8) / 10
def f1(x):
    return -(x**3 - 2*x**2 + 8) / 10

# Проверка сходимости на интервале [-1, 0]:
# Производная f'(x) = -(3x^2 - 4x) / 10.
# В точках -1 и 0: f'(-1) = -(3 + 4)/10 = -0.7, f'(0) = 0.
# |f'(x)| < 1 на интервале, значит метод сойдется.

def iteration_method(f, x0, tol=0.001, max_iter=100):
    x_curr = x0
    for i in range(max_iter):
        x_next = f(x_curr)
        if abs(x_next - x_curr) < tol:
            return x_next, i + 1
        x_curr = x_next
    return x_curr, max_iter

print("\nУравнение 1: x^3 - 2x^2 + 10x + 8 = 0")
# Начальное приближение возьмем середину интервала [-1, 0] -> -0.5
root1, iters1 = iteration_method(f1, -0.5, tol=0.001)
print(f"Корень: x ≈ {root1:.4f} (найден за {iters1} итераций)")
# Проверка подстановкой:
print(f"Проверка: {root1**3 - 2*root1**2 + 10*root1 + 8:.5f} (должно быть близко к 0)")

# --- Уравнение 2: cos(x) + 2x = 0 ---
# Отделение: f(0) = 1, f(-1) = cos(-1) - 2 = 0.54 - 2 = -1.46.
# Корень на интервале [-1, 0].
# Приводим к виду x = f(x): x = -cos(x) / 2
def f2(x):
    return -cos(x) / 2

# Проверка сходимости:
# Производная f'(x) = sin(x) / 2. На [-1, 0] |f'(x)| <= sin(1)/2 ~ 0.42 < 1. Сходится.

print("\nУравнение 2: cos(x) + 2x = 0")
# Начальное приближение x0 = -0.5
